STEM_RE = re.compile(r"^[a-z][a-z0-9_]*$")
JS_IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
REF_PREFIX = "#/$defs/"


@dataclass(frozen=True)
class Export:
    """One exported type: where to import it from and what to call the JSON Schema."""

    module: str
    attr: str
    stem: str


